#!/usr/bin/env python3
"""Resolve the EL7 (CentOS 7.9.2009) packages used by the el7-runtime module
to exact RPM URLs + SHA-256 checksums taken from the official repository
metadata, and write external/package/el7-runtime/el7-ARCH.lock and
el7-runtime-ARCH.hash.  Run again only to deliberately update the pin.

    python3 scripts/el7-lock.py aarch64     # AltArch tree
    python3 scripts/el7-lock.py x86_64      # main tree
"""
import gzip, os, sys, urllib.request, xml.etree.ElementTree as ET

ARCH = sys.argv[1] if len(sys.argv) > 1 else "aarch64"
BASE = {"aarch64": "https://vault.centos.org/altarch/7.9.2009",
        "x86_64": "https://vault.centos.org/7.9.2009"}[ARCH]
REPOS = ["updates", "os"]          # updates first: newest builds win
ARCHES = (ARCH, "noarch")

# Runtime libraries + the real EL7 programs used by the compatibility tests.
PACKAGES = """
glibc glibc-common libgcc libstdc++ zlib bzip2-libs xz-libs lz4
ncurses-libs ncurses-base readline pcre libselinux libsepol libattr libacl libcap
openssl openssl-libs krb5-libs keyutils-libs libcom_err libverto
nss-softokn-freebl libuuid libblkid libffi sqlite expat gmp mpfr elfutils-libelf
bash coreutils gawk sed grep tree bc which zip unzip file file-libs findutils
""".split()

NS = {"c": "http://linux.duke.edu/metadata/common",
      "r": "http://linux.duke.edu/metadata/repo"}

def fetch(url):
    with urllib.request.urlopen(url, timeout=120) as f:
        return f.read()

def vercmp_key(v):
    # good enough for picking the newest build of one package name within EL7
    import re
    return [int(x) if x.isdigit() else x for x in re.split(r"[.\-_]", v)]

best = {}
for repo in REPOS:
    root = f"{BASE}/{repo}/{ARCH}"
    repomd = ET.fromstring(fetch(f"{root}/repodata/repomd.xml"))
    href = next(d.find("r:location", NS).get("href")
                for d in repomd.findall("r:data", NS) if d.get("type") == "primary")
    primary = ET.fromstring(gzip.decompress(fetch(f"{root}/{href}")))
    for p in primary.findall("c:package", NS):
        name, arch = p.find("c:name", NS).text, p.find("c:arch", NS).text
        if name not in PACKAGES or arch not in ARCHES:
            continue
        v = p.find("c:version", NS)
        evr = (int(v.get("epoch") or 0), vercmp_key(v.get("ver")), vercmp_key(v.get("rel")))
        loc = p.find("c:location", NS).get("href")
        cs = p.find("c:checksum", NS)
        if cs.get("type") != "sha256":
            sys.exit(f"{name}: unexpected checksum type {cs.get('type')}")
        lic = p.find("c:format/{http://linux.duke.edu/metadata/rpm}license", NS)
        src = p.find("c:format/{http://linux.duke.edu/metadata/rpm}sourcerpm", NS)
        cand = (evr, f"{root}/{loc}", cs.text, lic.text if lic is not None else "?",
                src.text if src is not None else "?")
        if name not in best or cand[0] > best[name][0]:
            best[name] = cand

missing = sorted(set(PACKAGES) - set(best))
if missing:
    sys.exit("not found in repos: " + " ".join(missing))

out = os.path.join(os.path.dirname(__file__), "..", "external", "package", "el7-runtime")
with open(os.path.join(out, f"el7-{ARCH}.lock"), "w") as f:
    f.write("# name url sha256 license source-rpm  (generated by scripts/el7-lock.py)\n")
    for n in sorted(best):
        _, url, sha, lic, src = best[n]
        f.write(f"{n} {url} {sha} {lic.replace(' ', '_')} {src}\n")
with open(os.path.join(out, f"el7-runtime-{ARCH}.hash"), "w") as f:
    f.write(f"# From CentOS 7.9.2009 {ARCH} repodata (primary.xml sha256)\n")
    for n in sorted(best):
        _, url, sha, _, _ = best[n]
        f.write(f"sha256  {sha}  {url.rsplit('/', 1)[1]}\n")
print(f"pinned {len(best)} {ARCH} packages")
